const items = [
	"पारण अगले दिन ,सुबह 9:30 के पूर्व । ",
	"पारण – सुबह 9:30 के पूर्व ।",
	"पारण 09:25 के पूर्व ।",
	"पारण – सुबह 9:30 के पूर्व l",
	"पारण 9:30am पूर्व। (दूसरे दिन)",
	"पारण 5:53am के पूर्व।",
	" पारण 6:17am के पूर्व।",
	"पारण- अगली सुबह 9:30 के पूर्व",
	"पारण-सुबह 9:30 के पूर्व ",
	"अगले दिन सुबह 9:30 के पूर्व।",
	"22/11/26 सुबह 9:30 के  पूर्व ",
];
items.forEach((t) => {
	let clean = t.trim();
	clean = clean.replace(/^(?:पारण\s*[-–—:]*\s*)/i, "");
	clean = clean.replace(/^(?:अगले दिन|अगली सुबह|कल)\s*[,:-]?\s*/i, "");
	clean = clean.replace(/\(दूसरे दिन\)/i, "");
	clean = clean.replace(/\s+l\s*$/, " ।");
	clean = clean.trim();
	console.log(`${t}  =>  ${clean}`);
});
