const tests = [
	"पारण अगले दिन ,सुबह 9:30 के पूर्व ।",
	"पारण: 09:30 के पूर्व",
	"पारण कल सुबह 9:30",
	"पारण - सुबह 9:30 के पूर्व",
];
tests.forEach((t) => {
	let c = t;
	c = c.replace(/^पारण\s*[-:]?\s*/, "");
	c = c.replace(/^अगले दिन\s*[,:-]?\s*/, "");
	c = c.replace(/^कल\s*[,:-]?\s*/, "");
	console.log(`${t}  =>  ${c}`);
});
